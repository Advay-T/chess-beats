// Build library.js from data/pgn/*.pgn and games.js.
// Run: npm run build:library
// Every game is parsed with chess.js and analysed with analysis.js, so the page can show
// the peak-tension position and a tension sparkline without parsing anything at load time.
const fs = require("node:fs");
const path = require("node:path");
const { Chess } = require("chess.js");
const ChessAnalysis = require("../analysis.js");
const ChessPgn = require("../pgn.js");
const BUILTIN_GAMES = require("../games.js");
const { normalize } = require("./pgn-normalize.js");
const { CATEGORIES, COLLECTIONS } = require("./collections.js");

const ROOT = path.join(__dirname, "..");
const SPARK_POINTS = 40;
const MAX_FAILURES = 3;
const MENTOR_FILE = "data/pgn/pgnmentor-selected.pgn";

const clean = (v) => (v && !/^\?+$/.test(v) && !/^[?.]+$/.test(v) ? v : "");
const surname = (name) => {
  const n = clean(name).trim();
  if (!n) return "?";
  if (n.includes(",")) return n.split(",")[0].trim(); // "Van Wely, Loek" -> "Van Wely"
  const parts = n.split(/\s+/);
  return parts[parts.length - 1]; // "Robert James Fischer" -> "Fischer"
};

function record(collection, index, pgn, name) {
  const g = ChessPgn.parse(pgn, Chess, ChessAnalysis);
  const h = g.headers;
  const a = g.analysis;
  const frames = a.frames;
  const n = frames.length;
  const spark = [];
  const points = Math.min(SPARK_POINTS, n);
  for (let k = 0; k < points; k++) {
    const i = points === 1 ? 0 : Math.round((k * (n - 1)) / (points - 1));
    spark.push(Math.round(frames[i].tension * 100) / 100);
  }
  const peakPly = a.summary.peak.ply;
  const pm = peakPly > 0 ? g.moves[peakPly - 1] : null;
  const year = +(clean(h.Date).match(/^(\d{4})/) || [])[1] || null;
  return {
    id: collection + "-" + String(index + 1).padStart(2, "0"),
    collection,
    name: name || "",
    white: clean(h.White) || "White",
    black: clean(h.Black) || "Black",
    title: surname(h.White) + " – " + surname(h.Black),
    year,
    date: clean(h.Date),
    event: clean(h.Event),
    site: clean(h.Site),
    result: g.result,
    eco: clean(h.ECO),
    plies: n,
    mate: g.mate,
    profile: a.summary.profile,
    captures: a.summary.captures,
    checks: a.summary.checks,
    avgTension: Math.round(a.summary.avgTension * 1000) / 1000,
    peakPly,
    peakFen: g.fens[peakPly].split(" ")[0],
    peakMove: pm ? { from: pm.from, to: pm.to, color: pm.color, san: pm.san } : null,
    spark,
    auto: a.auto,
    pgn,
  };
}

function build() {
  const games = [];
  const failures = [];
  const counts = {};

  // PGN Mentor selections live in one file, tagged [Collection "<id>"].
  const mentor = {};
  if (fs.existsSync(path.join(ROOT, MENTOR_FILE))) {
    normalize(fs.readFileSync(path.join(ROOT, MENTOR_FILE), "utf8")).forEach((x) => {
      (mentor[x.headers.Collection] = mentor[x.headers.Collection] || []).push({ pgn: x.pgn });
    });
  }

  for (const c of COLLECTIONS) {
    let sources;
    if (c.source === "pgnmentor") {
      sources = mentor[c.id] || [];
    } else if (c.source === "book") {
      sources = normalize(fs.readFileSync(path.join(ROOT, c.file), "utf8")).map((x) => ({ pgn: x.pgn }));
    } else {
      sources = BUILTIN_GAMES.map((x) => ({ pgn: x.pgn, name: x.title.replace(/\s*\(\d{4}\)$/, "") }));
    }
    const list = [];
    sources.forEach((s, i) => {
      try {
        list.push(record(c.id, i, s.pgn, s.name));
      } catch (e) {
        failures.push(c.id + " #" + (i + 1) + ": " + e.message + "\n      " + s.pgn.split("\n").filter((l) => l.startsWith("[White") || l.startsWith("[Black") || l.startsWith("[Date")).join(" "));
      }
    });
    // Chronological within a collection (stable: book order breaks ties).
    list.sort((x, y) => (x.year || 9999) - (y.year || 9999) || (x.date < y.date ? -1 : x.date > y.date ? 1 : 0));
    counts[c.id] = list.length;
    games.push(...list);
  }

  console.log("Library:");
  for (const cat of CATEGORIES) {
    const cs = COLLECTIONS.filter((c) => c.category === cat.id);
    console.log("  " + cat.title + ": " + cs.reduce((s, c) => s + counts[c.id], 0) + " games");
    console.log("    " + cs.map((c) => c.id + " " + counts[c.id]).join(", "));
  }
  if (failures.length) {
    console.log("Skipped " + failures.length + ":");
    failures.forEach((f) => console.log("  - " + f));
  }
  if (failures.length > MAX_FAILURES) {
    console.error("Too many games failed to parse; library.js not written.");
    process.exit(1);
  }

  const data = {
    categories: CATEGORIES,
    collections: COLLECTIONS.map(({ id, title, subtitle, category }) => ({ id, title, subtitle, category, count: counts[id] })),
    games,
  };
  const out =
    "// GENERATED by tools/build-library.js — do not edit. Run `npm run build:library`.\n" +
    "// Sources: github.com/brianerdelyi/ChessPGN (CC0) and pgnmentor.com. See data/pgn/README.md.\n" +
    "(function (root) {\n  var GAME_LIBRARY = " +
    JSON.stringify(data) +
    ";\n  if (typeof module !== \"undefined\" && module.exports) module.exports = GAME_LIBRARY;\n  else root.GAME_LIBRARY = GAME_LIBRARY;\n})(this);\n";
  fs.writeFileSync(path.join(ROOT, "library.js"), out);
  console.log("Wrote library.js (" + Math.round(out.length / 1024) + " KB, " + games.length + " games)");
}

build();
